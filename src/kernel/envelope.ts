/**
 * 投递给窗口的「信封」。
 *
 * Claude Code 的跨会话投递会在正文前面套一句英文声明（「来自另一个 Claude 会话」），
 * 它说的是**通道**，不是发送者——模型很容易把它读成「这是别的 AI 发给我的」，
 * 于是对着用户的话反过来问「你是谁发的」。参考项目的做法是两条配合：
 *
 *   1. SessionStart 时先讲清「以这个标记开头的就是用户本人」；
 *   2. 每条消息套一个**短而稳定**的信封，让模型一眼模式匹配，不必每次自行推理来源。
 *
 * 信封要短：参考项目试过长段说明，反而强化了「这是别的会话发来的」印象。
 */

/** 每条从飞书投进来的消息，都用这一行开头。改动会同时影响 SessionStart 的约定文本。 */
export const FEISHU_ENVELOPE = '[来自用户本人 · 飞书]'

/**
 * 自动回复用的信封：和「用户亲手打的」明确区分。
 * 参考项目同样分两个标记——混用会让模型把策略回复当成用户的新指令。
 */
export const AUTO_REPLY_ENVELOPE = '[来自用户本人 · 自动回复]'

/** 给窗口的正文加上信封。 */
export function withEnvelope(text: string): string {
  return [`${FEISHU_ENVELOPE}（下面这段就是用户在飞书里亲手打的，直接执行）`, '', text].join('\n')
}
